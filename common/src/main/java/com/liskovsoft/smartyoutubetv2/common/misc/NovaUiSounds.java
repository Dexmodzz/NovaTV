package com.liskovsoft.smartyoutubetv2.common.misc;

import android.app.Activity;
import android.content.Context;
import android.media.AudioAttributes;
import android.media.SoundPool;
import android.os.SystemClock;
import android.provider.Settings;
import android.view.KeyEvent;
import android.view.View;

import com.liskovsoft.smartyoutubetv2.common.R;
import com.liskovsoft.smartyoutubetv2.common.prefs.NovaTVData;

/**
 * NovaTV: soft navigation sounds, in place of the system click (muted in the app themes with
 * {@code android:soundEffectsEnabled=false}).<br/>
 * A short sound when the remote moves the selection, the same one a bit lower on OK.
 * 15 sounds to choose from in the NovaTV settings (default: a wooden "tock").
 * Volume (or off) from the NovaTV settings. Silent when the system sound effects are turned off in the TV settings.
 */
public final class NovaUiSounds {
    private static final long MIN_INTERVAL_MS = 55; // holding a direction key repeats fast
    /** Volumes per level (NovaTVData.UI_SOUNDS_*): off, quiet, normal */
    private static final float[] FOCUS_VOLUMES = {0f, 0.025f, 0.055f};
    private static final float[] SELECT_VOLUMES = {0f, 0.03f, 0.07f};
    /** Generated by tools/novatv/gen_sounds.py */
    private static final int[] SOUNDS = {
            R.raw.novatv_sound_01, R.raw.novatv_sound_02, R.raw.novatv_sound_03, R.raw.novatv_sound_04,
            R.raw.novatv_sound_05, R.raw.novatv_sound_06, R.raw.novatv_sound_07, R.raw.novatv_sound_08,
            R.raw.novatv_sound_09, R.raw.novatv_sound_10, R.raw.novatv_sound_11, R.raw.novatv_sound_12,
            R.raw.novatv_sound_13, R.raw.novatv_sound_14, R.raw.novatv_sound_15};
    /** OK plays the same sound a bit lower */
    private static final float SELECT_RATE = 0.8f;
    private static SoundPool sPool;
    private static int[] sSoundIds;
    private static long sLastPlayMs;

    private NovaUiSounds() {
    }

    /**
     * Call for every key event the activity dispatches (before handling it).
     */
    public static void onKey(Activity activity, KeyEvent event) {
        if (event.getAction() != KeyEvent.ACTION_DOWN || !isEnabled(activity)) {
            return;
        }

        int level = NovaTVData.instance(activity).getUiSounds();
        if (level == NovaTVData.UI_SOUNDS_OFF) {
            return;
        }

        switch (event.getKeyCode()) {
            case KeyEvent.KEYCODE_DPAD_UP:
            case KeyEvent.KEYCODE_DPAD_DOWN:
            case KeyEvent.KEYCODE_DPAD_LEFT:
            case KeyEvent.KEYCODE_DPAD_RIGHT:
                View decor = activity.getWindow() != null ? activity.getWindow().peekDecorView() : null;
                if (decor == null) {
                    return;
                }
                init(activity);
                View before = activity.getCurrentFocus();
                // The focus moves after the key is dispatched: only a real move makes a sound
                decor.post(() -> {
                    View after = activity.getCurrentFocus();
                    if (after != null && after != before) {
                        play(getSoundId(activity), FOCUS_VOLUMES[level], 1f);
                    }
                });
                break;
            case KeyEvent.KEYCODE_DPAD_CENTER:
            case KeyEvent.KEYCODE_ENTER:
            case KeyEvent.KEYCODE_NUMPAD_ENTER:
                View focus = activity.getCurrentFocus();
                if (event.getRepeatCount() == 0 && focus != null && focus.isClickable()) {
                    init(activity);
                    play(getSoundId(activity), SELECT_VOLUMES[level], SELECT_RATE);
                }
                break;
        }
    }

    /**
     * Load the sounds in advance (the first one would be missed otherwise).
     */
    public static void preload(Context context) {
        init(context);
    }

    /**
     * Settings: let the user hear the chosen level and sound (off is previewed at the normal level).
     */
    public static void preview(Context context) {
        int level = NovaTVData.instance(context).getUiSounds();
        if (level == NovaTVData.UI_SOUNDS_OFF) {
            level = NovaTVData.UI_SOUNDS_NORMAL;
        }

        init(context);
        sLastPlayMs = 0;
        play(getSoundId(context), FOCUS_VOLUMES[level], 1f);
    }

    public static int getSoundCount() {
        return SOUNDS.length;
    }

    private static int getSoundId(Context context) {
        int type = NovaTVData.instance(context).getUiSoundType();
        return sSoundIds[type < sSoundIds.length ? type : 0];
    }

    private static boolean isEnabled(Context context) {
        try {
            return Settings.System.getInt(context.getContentResolver(), Settings.System.SOUND_EFFECTS_ENABLED, 1) != 0;
        } catch (SecurityException e) {
            return true;
        }
    }

    private static void init(Context context) {
        if (sPool != null) {
            return;
        }

        sPool = new SoundPool.Builder()
                .setMaxStreams(3)
                .setAudioAttributes(new AudioAttributes.Builder()
                        .setUsage(AudioAttributes.USAGE_ASSISTANCE_SONIFICATION)
                        .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                        .build())
                .build();
        Context app = context.getApplicationContext();
        sSoundIds = new int[SOUNDS.length];
        for (int i = 0; i < SOUNDS.length; i++) {
            sSoundIds[i] = sPool.load(app, SOUNDS[i], 1); // small files, all ready for the preview
        }
    }

    private static void play(int soundId, float volume, float rate) {
        long now = SystemClock.uptimeMillis();
        if (sPool == null || now - sLastPlayMs < MIN_INTERVAL_MS) {
            return;
        }

        sLastPlayMs = now;
        sPool.play(soundId, volume, volume, 1, 0, rate);
    }
}
